import { expect, test } from 'bun:test';
import { createHash } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { z } from 'zod';
import {
  AgentStoreTransitionRecordSchema,
  createAgentStateSlotStore,
  createMemoryAgentRuntimeStore,
  decodeAgentConversationArchive,
  defineStateSlot,
  encodeAgentConversationArchive,
} from '../src/entrypoints/agent-runtime';
import { createBunSqliteAgentRuntimeStore } from '../src/entrypoints/agent-runtime/sqlite/bun';
import { branch } from './support/agent-branch-fixture';
import { branchRuntime } from './support/agent-branch-runtime-fixture';

// Unmodified public 0.109.4 export, SQLite schema 4, generated by the installed
// streaming fixture. Synthetic data only; this hash prevents rewriting the witness.
const legacyPath = new URL(
  '../scripts/consumer-lane/fixtures/node/src/agent-conversation-streaming-v0.109.4.json',
  import.meta.url,
);
const legacy = new Uint8Array(await Bun.file(legacyPath).arrayBuffer());

test('schema v4 public 0.109.4 streaming archive retains exact tools, compacted history and artifacts across retry/reopen', async () => {
  expect(createHash('sha256').update(legacy).digest('hex')).toBe(
    '3a1fb102dce2ea6b34ea116c0c7ec9d33f5045783b869c40cacd1631fedc1f6a',
  );
  const root = await mkdtemp(join(tmpdir(), 'stitchkit-stream-'));
  let sqlite = createBunSqliteAgentRuntimeStore({ filename: join(root, 'state.sqlite') });
  const archive = decodeAgentConversationArchive(legacy);
  try {
    await sqlite.store.importConversation(legacy);
    expect(await sqlite.store.exportConversation(archive.conversationId)).toEqual(legacy);
    const terminal = archive.events
      .map((event) =>
        event.kind === 'runtime/transition'
          ? AgentStoreTransitionRecordSchema.parse(event.payload)
          : undefined,
      )
      .find((record) => record?.type === 'terminal');
    if (terminal?.type !== 'terminal') throw new Error('Missing real terminal');
    const request = {
      requestKey: 'saved-request',
      destinationConversationId: 'copy',
      source: {
        kind: 'conversation',
        conversationId: archive.conversationId,
        throughRunId: terminal.input.runId,
      },
      artifactAuthorization: { operation: 'read', path: 'new-owner' },
    } satisfies Parameters<typeof branch>[1];
    const created = await branch(sqlite.store, request);
    const exact = await sqlite.store.loadSnapshot('copy');
    expect(exact.messages).toHaveLength(2);
    expect(
      exact.messages
        .flatMap((message) => message.parts)
        .filter((part) => part.type === 'tool-call' || part.type === 'tool-result'),
    ).toHaveLength(2);
    expect(exact.runs[0]?.ownerId).toBeUndefined();
    await sqlite.close();
    sqlite = createBunSqliteAgentRuntimeStore({ filename: join(root, 'state.sqlite') });
    expect(await branch(sqlite.store, request)).toEqual({
      outcome: 'duplicate',
      receipt: created.receipt,
    });
    const seen: string[] = [];
    const runtime = branchRuntime(sqlite.store, (prompt) => seen.push(JSON.stringify(prompt)));
    try {
      await runtime.submit({
        conversationId: 'copy',
        idempotencyKey: 'next',
        context: {},
        metadata: {},
        parts: [{ type: 'text', text: 'continue saved context' }],
      }).result;
    } finally {
      await runtime.close();
    }
    expect(seen[0]).toContain('retain the original streamed question');
    expect(seen[0]).toContain('tool evidence');
    expect(seen[0]).toContain('streamed answer');
    expect(await branch(sqlite.store, request)).toEqual({
      outcome: 'duplicate',
      receipt: created.receipt,
    });
    await expect(
      branch(sqlite.store, { ...request, source: { kind: 'archive', bytes: legacy } }),
    ).rejects.toThrow('conflicts');
    for (const store of [sqlite.store, createMemoryAgentRuntimeStore()]) {
      await branch(store, {
        ...request,
        destinationConversationId: 'restore',
        source: { kind: 'archive', bytes: legacy },
      });
      const restored = await store.loadSnapshot('restore');
      expect(restored.messages.map((message) => message.role)).toEqual(['summary']);
      expect(restored.messages[0]?.parts).toEqual([
        { type: 'text', text: 'compacted streamed context' },
      ]);
      const exported = decodeAgentConversationArchive(
        await store.exportConversation('restore'),
      );
      expect(exported.spills).toHaveLength(1);
      expect(exported.projections).toHaveLength(1);
      expect(JSON.stringify(exported.events)).toContain('tool evidence');
      expect(JSON.stringify(exported.events)).toContain(
        'retain the original streamed question',
      );
      const state = createAgentStateSlotStore({
        store,
        definitions: [defineStateSlot({ name: 'permission', schema: z.boolean() })],
      });
      expect(await state.get('restore', 'permission')).toBeUndefined();
      expect(
        exported.events.filter((event) =>
          ['state/set', 'durability/effect'].includes(event.kind),
        ),
      ).toHaveLength(0);
      expect(
        exported.events.filter((event) => event.kind === 'runtime/branch-observation'),
      ).toHaveLength(3);
    }
    expect(await sqlite.store.exportConversation(archive.conversationId)).toEqual(legacy);
  } finally {
    await sqlite.close();
    await rm(root, { recursive: true, force: true });
  }
});

test('the public journal inspection contract and branch accept both full and shortened checkpoints', async () => {
  const archive = decodeAgentConversationArchive(legacy);
  const terminal = archive.events
    .map((event) =>
      event.kind === 'runtime/transition'
        ? AgentStoreTransitionRecordSchema.parse(event.payload)
        : undefined,
    )
    .find((record) => record?.type === 'terminal');
  if (terminal?.type !== 'terminal') throw new Error('Missing terminal');
  let checkpoints = 0;
  archive.events = archive.events.map((event) => {
    if (event.kind !== 'runtime/transition') return event;
    const record = AgentStoreTransitionRecordSchema.parse(event.payload);
    if (record.type !== 'checkpoint') return event;
    checkpoints++;
    const payload = {
      ...record,
      input: {
        ...record.input,
        assistant: { ...terminal.input.assistant, status: 'streaming' },
      },
    };
    expect(AgentStoreTransitionRecordSchema.safeParse(payload).success).toBe(true);
    return { ...event, payload: z.json().parse(payload) };
  });
  expect(checkpoints).toBeGreaterThan(0);
  const store = createMemoryAgentRuntimeStore();
  await branch(store, {
    requestKey: 'full',
    destinationConversationId: 'full',
    source: { kind: 'archive', bytes: encodeAgentConversationArchive(archive) },
    artifactAuthorization: { operation: 'read', path: 'destination' },
  });
  expect((await store.loadSnapshot('full')).messages[0]?.role).toBe('summary');
});

test('malformed companion and checkpoint payloads refuse before any destination write', async () => {
  const original = decodeAgentConversationArchive(legacy);
  const projection = original.projections[1];
  if (projection === undefined) throw new Error('Missing companion projection');
  const record = original.events.find(
    (event) =>
      event.kind === 'runtime/transition' &&
      AgentStoreTransitionRecordSchema.parse(event.payload).type === 'checkpoint',
  );
  if (!record) throw new Error('Missing shortened checkpoint');
  for (const [index, archive] of [
    { ...original, projections: [...original.projections, projection] },
    {
      ...original,
      projections: [
        ...original.projections,
        { name: 'future', version: 1, uptoSeq: 1000000, value: {}, updatedAt: 'time' },
      ],
    },
    {
      ...original,
      projections: [
        ...original.projections,
        { archiveType: 'opaque-encrypted', bytes: 'not understood' },
      ],
    },
    {
      ...original,
      events: original.events.map((event) =>
        event === record
          ? {
              ...event,
              payload: {
                type: 'checkpoint',
                input: {
                  conversationId: original.conversationId,
                  runId: 'foreign',
                  expectedRevision: 1,
                  ownerId: 'owner',
                  assistant: {
                    id: 'foreign',
                    status: 'streaming',
                    sha256: 'damaged',
                    parts: 1,
                    bytes: 1,
                  },
                },
              },
            }
          : event,
      ),
    },
    { ...original, conversationId: 'foreign' },
  ].entries()) {
    const store = createMemoryAgentRuntimeStore();
    const id = `invalid-${index}`;
    await expect(
      branch(store, {
        requestKey: id,
        destinationConversationId: id,
        source: { kind: 'archive', bytes: encodeAgentConversationArchive(archive) },
        artifactAuthorization: { operation: 'read', path: 'destination' },
      }),
    ).rejects.toThrow();
    expect((await store.loadSnapshot(id)).version).toBe(0);
    expect((await store.readEvents({ conversationId: id, limit: 100 })).items).toHaveLength(0);
  }
});
